from pathlib import Path
import numpy as np
import pandas as pd
from matplotlib import pyplot as plt
# IMPORTANT: pip install autorank
from autorank import autorank, plot_stats, create_report

FILE_NAME = "results_per_split.csv"
PLOT_NAME = "relative_performance_v2.png"
PLOT_TITLE = "Statistical Significance of Methods (Critical Difference Plot)"

METRIC_DIRECTIONS = {
    "log_loss": True,  # Lower error is better
    "rmse": True,  # Lower error is better
    "roc_auc": False,  # Higher performance is better
}


def prepare_data_for_autorank(df):
    """
    Transforms the long-format dataframe into the wide-format block design
    required by Autorank: Rows = Datasets, Columns = Feature Selection Methods.
    """
    # 1. Get the columns we need to group by (usually metric and dataset)
    group_cols = [c for c in ["metric", "tid"] if c in df.columns]
    if not group_cols:
        group_cols = ["metric"]

    required_cols = group_cols + ["feature_selection_method", "metric_error"]
    df_clean = df.dropna(subset=required_cols).copy()

    # 2. Adjust metric values so "Lower is ALWAYS Better"
    # Autorank naturally ranks lower values as better when order='ascending' is used.
    def adjust_direction(row):
        is_lower_better = METRIC_DIRECTIONS.get(row["metric"], True)
        if is_lower_better:
            return row["metric_error"]
        else:
            return -row["metric_error"]  # Invert so lower is better

    df_clean["autorank_error"] = df_clean.apply(adjust_direction, axis=1)

    # 3. Average across CV splits/repeats so we have exactly ONE value per (Dataset, Method)
    df_collapsed = df_clean.groupby(
        group_cols + ["feature_selection_method"]
    )["autorank_error"].mean().reset_index()

    # 4. Pivot the dataframe to Block Design (Rows = Datasets, Columns = Methods)
    # If there are multiple metrics, we'll combine metric+dataset into the index
    if "tid" in group_cols:
        pivot_idx = ["metric", "tid"] if "metric" in group_cols else "dataset"
    else:
        # Fallback if no dataset column is present (assumes rows are just splits/repeats)
        pivot_idx = df_collapsed.index
    df_wide = df_collapsed.pivot(
        index=pivot_idx,
        columns="feature_selection_method",
        values="autorank_error"
    )

    # Drop any datasets/rows that don't have results for ALL methods
    # Autorank requires paired data (every method must be evaluated on the same datasets)
    df_wide = df_wide.dropna()

    return df_wide


def plot_autorank(df):
    # 1. Prepare the dataframe
    data = prepare_data_for_autorank(df)

    # 2. Run the autorank statistical analysis
    # We use order="ascending" because we manipulated the data so lower is always better [cite:520, 530]
    result = autorank(data, alpha=0.05, verbose=False, order='ascending')

    # Optional: Print the formal text report generated by Autorank
    create_report(result)

    # 3. Create the Critical Difference (CD) Plot
    fig, ax = plt.subplots(figsize=(10, sum(data.shape) / 4 + 2))  # Dynamic size based on method count

    # plot_stats handles the drawing of the CD diagram
    plot_stats(result, ax=ax)

    ax.set_title(PLOT_TITLE, pad=20, fontsize=14, weight='bold')

    plt.tight_layout()
    out = OUTPUT_DIR / PLOT_NAME
    plt.savefig(out, dpi=300, bbox_inches="tight")
    plt.close()

    print(f"✅ Autorank CD plot saved to {out}")


SCRIPT_DIR = Path(__file__).parent / "../../"
RESULTS_FILE = SCRIPT_DIR / "result_files" / FILE_NAME
OUTPUT_DIR = SCRIPT_DIR / "generated_plots/performance"
OUTPUT_DIR.mkdir(parents=True, exist_ok=True)


def main():
    df = pd.read_csv(RESULTS_FILE, low_memory=False)
    plot_autorank(df)


if __name__ == "__main__":
    main()